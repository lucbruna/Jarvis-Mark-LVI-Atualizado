def _resolve_folder(folder):
    home = Path.home()
    mapping = {"desktop": home / "Desktop", "documents": home / "Documents",
               "downloads": home / "Downloads", "home": home}
    p = mapping.get((folder or "documents").lower(), Path(folder).expanduser())
    p.mkdir(parents=True, exist_ok=True)
    return p


def _reveal(path):
    try:
        if sys.platform.startswith("win"):
            import subprocess
            subprocess.run(["explorer", "/select,", str(path)], check=False)
        elif sys.platform == "darwin":
            import subprocess
            subprocess.run(["open", "-R", str(path)], check=False)
        else:
            import subprocess
            subprocess.run(["xdg-open", str(path.parent)], check=False)
    except Exception:
        pass


def _build_docx(path, title, sections):
    try:
        from docx import Document
        from docx.shared import Pt, RGBColor
    except ImportError:
        return "python-docx not installed. Run: pip install python-docx"
    doc = Document()
    doc.add_heading(title, level=0)
    for s in sections or []:
        if s.get("heading"):
            doc.add_heading(s["heading"], level=1)
        for p in (s.get("paragraphs") or []):
            doc.add_paragraph(p)
        for b in (s.get("bullets") or []):
            doc.add_paragraph(b, style="List Bullet")
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(path)
    return f"Word document saved: {path}"


def _build_pptx(path, title, sections, slides):
    try:
        from pptx import Presentation
        from pptx.util import Inches, Pt
    except ImportError:
        return "python-pptx not installed. Run: pip install python-pptx"
    prs = Presentation()
    # title slide
    ts = prs.slides.add_slide(prs.slide_layouts[0])
    ts.shapes.title.text = title
    if ts.placeholders and len(ts.placeholders) > 1:
        ts.placeholders[1].text = "Generated by JARVIS"
    for s in (slides or []):
        sl = prs.slides.add_slide(prs.slide_layouts[1])
        sl.shapes.title.text = s.get("title", "")
        body = sl.placeholders[1]
        tf = body.text_frame
        tf.text = ""
        for b in (s.get("bullets") or []):
            p = tf.add_paragraph()
            p.text = b
            p.level = 0
        if s.get("notes"):
            sl.notes_slide.notes_text_frame.text = s["notes"]
    # fallback: convert sections to slides if no slides provided
    if not slides and sections:
        for s in sections:
            sl = prs.slides.add_slide(prs.slide_layouts[1])
            sl.shapes.title.text = s.get("heading", title)
            body = sl.placeholders[1]
            tf = body.text_frame
            tf.text = ""
            for p in (s.get("paragraphs") or []):
                pp = tf.add_paragraph()
                pp.text = p
            for b in (s.get("bullets") or []):
                pp = tf.add_paragraph()
                pp.text = b
    path.parent.mkdir(parents=True, exist_ok=True)
    prs.save(path)
    return f"PowerPoint saved: {path}"


def run(parameters: dict, player=None, session_memory=None) -> str:
    params = parameters or {}
    kind = (params.get("kind") or "docx").lower()
    title = (params.get("title") or "Document").strip()
    sections = params.get("sections") or []
    slides = params.get("slides") or []
    folder = params.get("folder") or "documents"
    base = (params.get("name") or title.replace(" ", "_"))[:40]
    out_dir = _resolve_folder(folder)
    stamp = int(time.time())
    if kind == "pptx":
        path = out_dir / f"{base}_{stamp}.pptx"
        msg = _build_pptx(path, title, sections, slides)
    else:
        path = out_dir / f"{base}_{stamp}.docx"
        msg = _build_docx(path, title, sections)
    if "not installed" not in msg:
        threading.Thread(target=_reveal, args=(path,), daemon=True).start()
    if player:
        try:
            player.write_log(f"JARVIS: {msg}")
        except Exception:
            pass
    return outcome.done("doc_builder", note=msg[:400])
