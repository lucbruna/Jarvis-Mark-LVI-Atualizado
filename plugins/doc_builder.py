"""JARVIS plugin - build Word documents and PowerPoint decks, delivered ready.

Complements bi_excel_builder: structured content -> real .docx/.pptx, opened
after creation. Uses python-docx and python-pptx when available.
"""
from __future__ import annotations

import sys
import threading
import time
from pathlib import Path

from core import outcome


